"""Deterministic, local scaffolds for new Python projects."""
from __future__ import annotations

import os
import keyword
import json
import re
from pathlib import Path
from typing import Mapping


def resolve_project_target(path: str | Path, cwd: str | Path | None = None) -> Path:
    """Resolve a new project directory beneath cwd without following symlinks."""
    root = Path(cwd or Path.cwd()).expanduser().resolve()
    raw = Path(path).expanduser()
    candidate = raw if raw.is_absolute() else root / raw
    candidate = Path(os.path.abspath(candidate))
    try:
        relative = candidate.relative_to(root)
    except ValueError as exc:
        raise ValueError("O diretório do projeto precisa ficar dentro da pasta atual.") from exc
    if not relative.parts:
        raise ValueError("Escolha uma nova pasta abaixo da pasta atual.")

    current = root
    for part in relative.parts:
        current = current / part
        if current.is_symlink():
            raise ValueError("O caminho do projeto não pode atravessar links simbólicos.")

    if current.exists():
        if not current.is_dir():
            raise ValueError("O destino existe e não é uma pasta.")
        if any(current.iterdir()):
            raise ValueError("A pasta de destino precisa estar vazia.")
    return current


def _package_name(directory_name: str) -> str:
    package = re.sub(r"[^a-zA-Z0-9_]+", "_", directory_name.lower()).strip("_")
    if not package:
        raise ValueError("O nome da pasta não pode formar um nome de pacote Python.")
    if package[0].isdigit():
        package = f"app_{package}"
    if keyword.iskeyword(package):
        package = f"app_{package}"
    return package


def build_scaffold(profile: str, directory_name: str, language: str = "python") -> dict[str, str]:
    """Return starter files for a supported language and CLI/API profile."""
    profile = profile.strip().lower()
    if profile not in {"cli", "api"}:
        raise ValueError("Perfil inválido. Escolha 'cli' ou 'api'.")
    language = language.strip().lower()
