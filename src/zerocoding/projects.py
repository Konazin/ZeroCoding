def _build_node_scaffold(language: str, profile: str, directory_name: str) -> dict[str, str]:
    name = re.sub(r"[^a-z0-9-]+", "-", directory_name.lower()).strip("-") or "new-project"
    if name[0].isdigit():
        name = f"project-{name}"
    typescript = language == "typescript"
    ext = "ts" if typescript else "js"
    source = "index" if profile == "cli" else "app"
    test = "index" if profile == "cli" else "app"
    package = {
        "name": name,
        "version": "0.1.0",
        "private": True,
        "type": "module",
        "engines": {"node": ">=24"},
        "scripts": {
            "start": f"node {'dist/' if typescript else 'src/'}{source}.{ext}",
            "test": "npm run build && node --test" if typescript else "node --test",
        },
    }
    if profile == "api":
        package["dependencies"] = {"fastify": "^5.2.0"}
    if typescript:
        package["scripts"]["build"] = "tsc -p tsconfig.json"
        package["devDependencies"] = {"@types/node": "^24.0.0", "typescript": "^5.9.0"}

    readme = f"""# {name}

{language.title()} {profile.upper()} project generated by ZeroCoding. Requires Node.js 24 or newer.

## Setup and run

```bash
npm install
npm start
```

## Test

```bash
npm test
```
"""
    files = {
        "package.json": json.dumps(package, indent=2) + "\n",
        ".gitignore": "node_modules/\ndist/\n.env\n",
        "README.md": readme,
    }
    if typescript:
        files["tsconfig.json"] = '''{
  "compilerOptions": {
    "target": "ES2022",
    "module": "NodeNext",
    "moduleResolution": "NodeNext",
    "rootDir": "src",
    "outDir": "dist",
    "strict": true,
    "esModuleInterop": true,
    "skipLibCheck": true
  },
  "include": ["src/**/*.ts"]
}
'''

    if profile == "cli":
        files[f"src/index.{ext}"] = '''#!/usr/bin/env node
import { parseArgs } from "node:util";
import { pathToFileURL } from "node:url";

export function main(argv = process.argv.slice(2)) {
  const { values } = parseArgs({ args: argv, options: { help: { type: "boolean" } }, allowPositionals: true });
  if (values.help) console.log("Usage: __NAME__ [options]");
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exitCode = main();
'''.replace("__NAME__", name)
        files["tests/index.test.js"] = '''import assert from "node:assert/strict";
import test from "node:test";
import { main } from "../dist/index.js";

test("main returns a successful exit code", () => {
  assert.equal(main([]), 0);
});
'''
    else:
        files[f"src/app.{ext}"] = '''import Fastify from "fastify";
import { pathToFileURL } from "node:url";

export const app = Fastify({ logger: false });

app.get("/health", async () => ({ status: "ok" }));

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await app.listen({ port: Number(process.env.PORT ?? 3000), host: "0.0.0.0" });
}
'''
        files["tests/app.test.js"] = '''import assert from "node:assert/strict";
import test, { after } from "node:test";
import { app } from "../dist/app.js";

after(() => app.close());

test("health endpoint returns status ok", async () => {
  const response = await app.inject({ method: "GET", url: "/health" });
  assert.equal(response.statusCode, 200);
  assert.deepEqual(response.json(), { status: "ok" });
});
'''
    if not typescript:
        # JavaScript tests import the source directly; TypeScript tests use built output.
        files[f"tests/{test}.test.js"] = files[f"tests/{test}.test.js"].replace("../dist/", "../src/")
    return files


def create_project(path: str | Path, profile: str, cwd: str | Path | None = None, language: str = "python") -> tuple[str, ...]:
    """Create scaffold files exclusively; existing files are never overwritten."""
    target = resolve_project_target(path, cwd=cwd)
    files = build_scaffold(profile, target.name, language=language)
    created_files: list[Path] = []
    created_dirs: list[Path] = []

    def ensure_directory(directory: Path, stop: Path | None = None) -> None:
        missing = []
        current = directory
        while current != stop and not current.exists():
            missing.append(current)
            current = current.parent
        for item in reversed(missing):
            item.mkdir()
            created_dirs.append(item)

    try:
        ensure_directory(target)
        for relative, content in files.items():
            output = target / relative
            ensure_directory(output.parent, stop=target)
            with output.open("x", encoding="utf-8", newline="\n") as stream:
                # Track immediately after exclusive creation so a partial write
                # is removed if the filesystem fails midway through the file.
                created_files.append(output)
                stream.write(content)
    except Exception:
        for output in reversed(created_files):
            try:
                output.unlink()
            except OSError:
                pass
        for directory in reversed(created_dirs):
            try:
                directory.rmdir()
            except OSError:
                pass
        raise
    return tuple(files)
